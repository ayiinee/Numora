// Generate structural TypeScript types from schemas. Cross-field invariants stay in validators.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const require = createRequire(
  process.env.NUMORA_REPO_PATH
    ? path.join(process.env.NUMORA_REPO_PATH, 'package.json')
    : new URL('../../../package.json', import.meta.url),
);
const { format } = require('prettier');

const read = (name) => JSON.parse(readFileSync(new URL(name, import.meta.url), 'utf8'));
const pascal = (name) => name[0].toUpperCase() + name.slice(1);
function typeOf(schema) {
  if (schema.$ref) return pascal(schema.$ref.split('/').at(-1));
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (schema.anyOf || schema.oneOf) return (schema.anyOf || schema.oneOf).map(typeOf).join(' | ');
  if (schema.type === 'array') return `Array<${typeOf(schema.items)}>`;
  if (schema.type === 'object')
    return (
      '{\n' +
      Object.entries(schema.properties || {})
        .map(
          ([k, v]) =>
            `  ${JSON.stringify(k)}${schema.required?.includes(k) ? '' : '?'}: ${typeOf(v)};`,
        )
        .join('\n') +
      '\n}'
    );
  return (
    { integer: 'number', number: 'number', string: 'string', boolean: 'boolean', null: 'null' }[
      schema.type
    ] || 'unknown'
  );
}
export async function renderTypes() {
  const lines = [
    '// Generated by generate-types.mjs. Do not edit; run with --check in CI.',
    '// Structural types only: call validators for provenance, eligibility and state invariants.',
  ];
  for (const [name, schema] of Object.entries(read('common.schema.json').$defs))
    lines.push(`export type ${pascal(name)} = ${typeOf(schema)};`);
  lines.push(`export type CalibrationInput = ${typeOf(read('input.schema.json'))};`);
  lines.push(`export type CalibrationResult = ${typeOf(read('result.schema.json'))};`);
  return format(lines.join('\n\n') + '\n', {
    parser: 'typescript',
    semi: true,
    singleQuote: true,
    trailingComma: 'all',
    printWidth: 100,
    endOfLine: 'lf',
  });
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = new URL('types.d.ts', import.meta.url),
    content = await renderTypes();
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== content) throw new Error('IRT generated types are stale');
    console.log('IRT generated types match schemas');
  } else writeFileSync(file, content);
}
